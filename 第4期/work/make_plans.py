def end_of(t):
    for s in segs:
        if abs(s['start'] - t) < 0.02:
            return round(s['end'], 2)
    return t


def P(a, b, text, **kw):
    return {'src_start': a, 'src_end': end_of(b), 'text': text, **kw}


def PP(parts, text, **kw):
    parts = [[a, end_of(b) if i == len(parts) - 1 and kw.pop('_last_seg', False) else b] for i, (a, b) in enumerate(parts)]
    return {'src_start': parts[0][0], 'src_end': parts[-1][1], 'parts': parts, 'text': text, 'inner_gap': 0.08, **kw}


def plan(speaker, cold, chapters):
    for c in cold + [p for ch in chapters for p in ch['pieces']]:
        c['speaker'] = speaker
    return {'cold_open': cold, 'chapters': chapters}


